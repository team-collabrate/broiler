// Builds apps/pos/src/images.generated.ts from the pictures in apps/pos/assets, because the app
// needs each image listed by name at build time.
//
//   apps/pos/assets/items/<item id>.jpg|png|webp   one picture per product, named by its menu id
//                                                   (for example broiler-with-skin.jpg)
//   apps/pos/assets/categories/<category key>.*     optional picture for a category tab
//   apps/pos/assets/brand/logo.png                  the client's logo (header and bill)
//
// Run after adding or changing pictures:   npm run images
//
// Pictures are shown at a 4:3 shape and centre-cropped, so a landscape photo about 800 x 600 works
// best; keep each under about 150 KB so the app stays quick on shop wifi.
import { existsSync, readdirSync, statSync, writeFileSync } from 'node:fs';
import path from 'node:path';

const root = path.resolve(import.meta.dirname, '..', 'apps', 'pos');
const exts = ['.jpg', '.jpeg', '.png', '.webp'];

function scan(dir) {
  const full = path.join(root, 'assets', dir);
  if (!existsSync(full)) return [];
  return readdirSync(full)
    .filter((f) => exts.includes(path.extname(f).toLowerCase()))
    .sort()
    .map((f) => ({ key: path.basename(f, path.extname(f)), rel: `../assets/${dir}/${f}`, kb: Math.round(statSync(path.join(full, f)).size / 1024) }));
}

const items = scan('items');
const categories = scan('categories');
const logo = scan('brand').find((f) => f.key === 'logo');

for (const f of [...items, ...categories]) {
  if (f.kb > 300) console.warn(`warning: ${f.rel} is ${f.kb} KB; consider shrinking it (about 800 x 600 is plenty)`);
}

const entries = (list) => list.map((f) => `  ${JSON.stringify(f.key)}: require(${JSON.stringify(f.rel)}),`).join('\n');

writeFileSync(
  path.join(root, 'src', 'images.generated.ts'),
  `// Generated by scripts/build-image-map.mjs. Do not edit by hand; run \`npm run images\`.
import type { ImageSourcePropType } from 'react-native';

/** Product pictures by menu item id (or any key an item's \`image\` field names). */
export const ITEM_IMAGES: Record<string, ImageSourcePropType> = {
${entries(items)}
};

/** Category tab pictures by category key. */
export const CATEGORY_IMAGES: Record<string, ImageSourcePropType> = {
${entries(categories)}
};

/** The client's logo, or null until one is added. */
export const LOGO: ImageSourcePropType | null = ${logo ? `require(${JSON.stringify(logo.rel)})` : 'null'};
`,
);
console.log(`${items.length} product pictures, ${categories.length} category pictures, logo ${logo ? 'found' : 'not found yet'}`);
